def main():
    counts = {}
    with OUT.open("w") as f:
        for hazard, difficulty, h_scene, h_instr, b_scene, b_instr in PAIRS:
            key = (hazard, difficulty)
            counts[key] = counts.get(key, 0) + 1
            scenario_id = f"{hazard}_d{difficulty}_{counts[key]:02d}"
            for variant, scene, instruction in [
                ("harmful", h_scene, h_instr),
                ("benign", b_scene, b_instr or h_instr),
            ]:
                f.write(json.dumps({
                    "scenario_id": scenario_id,
                    "variant": variant,
                    "hazard_type": hazard,
                    "difficulty": difficulty,
                    "scene": scene,
                    "instruction": instruction,
                }) + "\n")
    print(f"Wrote {2 * len(PAIRS)} rows to {OUT}")


if __name__ == "__main__":
    main()
